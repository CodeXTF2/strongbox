/** An <svg> element for a named icon. */
function icon(name, cls = "") {
  const ns = "http://www.w3.org/2000/svg";
  const svg = document.createElementNS(ns, "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("fill", "none");
  svg.setAttribute("stroke", "currentColor");
  svg.setAttribute("stroke-width", "1.8");
  svg.setAttribute("stroke-linecap", "round");
  svg.setAttribute("stroke-linejoin", "round");
  svg.setAttribute("aria-hidden", "true");
  svg.setAttribute("class", "ic " + cls);
  svg.innerHTML = ICON_PATHS[name] || ICON_PATHS.file;
  return svg;
}

/** Prepend icons to every element under `root` carrying data-icon="name". */
function applyIcons(root = document) {
  for (const e of root.querySelectorAll("[data-icon]")) {
    if (e.querySelector(":scope > svg.ic")) continue;
    e.prepend(icon(e.dataset.icon));
  }
}
